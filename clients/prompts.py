def format_history(history: list[str]) -> str:
    return "\n".join(
        ("Пользователь: " if i % 2 == 0 else "Ассистент: ") + history[i]
        for i in range(len(history))
    )

def format_chunks(chunks: list[str], starting: int, num_of_chunks: int) -> str:
    result = ""
    for ind, chunk in enumerate(chunks):
        result += f"--- BLOCK {starting + ind + 1} / {num_of_chunks} ---\n{chunk}\n\n"
    return result